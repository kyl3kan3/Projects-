/**
 * The launch curation set: 50 authorities having jurisdiction across the Phoenix
 * metro — every incorporated city and town in Maricopa County, the Pinal County
 * communities the metro spills into, both counties' unincorporated areas, the
 * tribal communities inside the valley, and the single-purpose authorities a
 * contractor still has to satisfy (utility interconnection, fire districts, air
 * quality, the state registrar).
 *
 * Depth-first, per README's coverage strategy: one metro covered completely
 * before a second one is promised. Each entry is what a curator would carry back
 * from the counter — the base permit fee, the inspection desk's own habits, and
 * the quirks that get a submittal rejected. `covers: "all"` means every job type
 * in the taxonomy has a verified record here; a list means only those do, and the
 * jurisdiction is honestly marked `partial`.
 *
 * This is seed data for a pre-launch product. Every record it produces carries a
 * source URL and a verified-at date, and the product never presents one without
 * them — the whole point of the corpus is that a contractor can see how old a
 * fact is before betting a crew on it.
 */

